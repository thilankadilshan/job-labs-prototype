/*
 * Job Labs prototype — fake back-end.
 *
 * The real site posts forms to Laravel (contact, job application, recruiter sign-up,
 * OTP, CV download...). This prototype is static, so this file (loaded first on every
 * page) answers those requests in the browser:
 *   1. window.fetch is wrapped: known Laravel endpoints get the same JSON/Blob the
 *      controllers return; everything else goes to the network untouched.
 *   2. Plain (non-AJAX) POST form submits are caught and redirected the way the
 *      controllers redirect.
 * Nothing is sent anywhere. Remove this file once a real API exists.
 */
(function () {
  'use strict';

  var json = function (data, status) {
    return new Response(JSON.stringify(data), { status: status || 200, headers: { 'Content-Type': 'application/json' } });
  };
  var delay = function (ms) { return new Promise(function (r) { setTimeout(r, ms); }); };
  var log = function () { if (window.console) console.info.apply(console, ['[prototype mock-api]'].concat([].slice.call(arguments))); };

  // Minimal one-page PDF so "Download PDF" in the CV builder produces a real file.
  function makePdf(lines) {
    var esc = function (s) { return String(s).replace(/[\\()]/g, '\\$&').replace(/[^\x20-\x7E]/g, '?'); };
    var text = 'BT /F1 22 Tf 60 780 Td (' + esc(lines[0]) + ') Tj /F1 12 Tf';
    for (var i = 1; i < lines.length; i++) text += ' 0 -22 Td (' + esc(lines[i]) + ') Tj';
    text += ' ET';
    var objs = [
      '<< /Type /Catalog /Pages 2 0 R >>',
      '<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
      '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 5 0 R >> >> /Contents 4 0 R >>',
      '<< /Length ' + text.length + ' >>\nstream\n' + text + '\nendstream',
      '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>'
    ];
    var out = '%PDF-1.4\n', offsets = [];
    objs.forEach(function (o, k) { offsets.push(out.length); out += (k + 1) + ' 0 obj\n' + o + '\nendobj\n'; });
    var xref = out.length;
    out += 'xref\n0 ' + (objs.length + 1) + '\n0000000000 65535 f \n';
    offsets.forEach(function (o) { out += ('000000000' + o).slice(-10) + ' 00000 n \n'; });
    out += 'trailer\n<< /Size ' + (objs.length + 1) + ' /Root 1 0 R >>\nstartxref\n' + xref + '\n%%EOF';
    return new Blob([out], { type: 'application/pdf' });
  }

  function cvLines(fd) {
    var g = function (k) { return fd && fd.get ? (fd.get(k) || '') : ''; };
    var name = (g('full_name') || g('name') || ((g('first_name') + ' ' + g('last_name')).trim()) || 'Your Name');
    return [name, g('email'), g('phone'), '', 'Generated by the Job Labs PROTOTYPE (mock data).',
      'The live site renders the full CV template on the server.'];
  }

  var routes = [
    // JobsBoardController@submitApplication  (POST /{job_id}/{slug}/apply)
    { test: /\/apply\/?$/, handle: function (url) {
        var jobUrl = url.pathname.replace(/\/apply\/?$/, '');
        return json({
          success: true,
          message: 'Your application has been submitted successfully! We will review your application and get back to you soon.',
          redirect_url: jobUrl
        });
      } },
    // ContactController@submit
    { test: /^\/contact\/submit\/?$/, handle: function () {
        return json({ success: true, message: "Thank you for your message! We'll get back to you within 24 hours." });
      } },
    // JobsBoardController@savePreferences
    { test: /^\/cookie-preferences\/?$/, handle: function () { return json({ success: true }); } },
    // JobsBoardController@getRecommendations (no server-side scoring in the prototype)
    { test: /recommendations\/?$/, handle: function () { return json({ jobs: [], count: 0 }); } },
    // CVBuilderController@generatePDF / generateWord
    { test: /^\/cv-builder\/generate-pdf\/?$/, handle: function (url, init) {
        return new Response(makePdf(cvLines(init && init.body)), { status: 200, headers: { 'Content-Type': 'application/pdf' } });
      } },
    { test: /^\/cv-builder\/generate-word\/?$/, handle: function (url, init) {
        var l = cvLines(init && init.body);
        var html = '<html><body><h1>' + l[0] + '</h1><p>' + l.slice(1).join('<br>') + '</p></body></html>';
        return new Response(new Blob([html], { type: 'application/msword' }), { status: 200 });
      } }
  ];

  var realFetch = window.fetch ? window.fetch.bind(window) : null;
  window.fetch = function (input, init) {
    try {
      var url = new URL(typeof input === 'string' ? input : input.url, window.location.href);
      var method = ((init && init.method) || (input && input.method) || 'GET').toUpperCase();
      if (url.origin === window.location.origin && method !== 'GET') {
        for (var i = 0; i < routes.length; i++) {
          if (routes[i].test.test(url.pathname)) {
            log(method, url.pathname, '-> mocked');
            var res = routes[i].handle(url, init);
            return delay(700).then(function () { return res; });
          }
        }
        log(method, url.pathname, '-> no mock, returning generic success');
        return delay(400).then(function () { return json({ success: true, message: 'Saved (prototype).' }); });
      }
    } catch (e) { /* fall through to the network */ }
    return realFetch(input, init);
  };

  // Plain POST form submits (no AJAX): mimic the Laravel redirects.
  var formRedirects = [
    // HomeController@userRequestForm -> OTP page
    { test: /^\/user\/request\/?$/, go: function (form) {
        var email = form.elements.user_email ? form.elements.user_email.value : '';
        try { sessionStorage.setItem('proto_signup_email', email); } catch (e) {}
        return '/signup/verify-otp';
      } },
    { test: /^\/signup\/verify-otp\/?$/, go: function () { return '/signup/thankyou'; } },
    { test: /^\/signup\/resend-otp\/?$/, go: function () { return '/signup/verify-otp'; } },
    // Auth\LoginController: the ATS dashboard is not part of the prototype
    { test: /^\/(ats|login)\/?$/, go: function () {
        alert('Prototype: signing in is disabled — the ATS / dashboard is not part of this prototype.');
        return null;
      } }
  ];
  window.addEventListener('submit', function (e) {
    var form = e.target;
    if (e.defaultPrevented || !form || (form.getAttribute('method') || 'get').toLowerCase() !== 'post') return;
    e.preventDefault();
    var path = new URL(form.getAttribute('action') || window.location.pathname, window.location.href).pathname;
    var next = window.location.pathname;
    for (var i = 0; i < formRedirects.length; i++) {
      if (formRedirects[i].test.test(path)) { next = formRedirects[i].go(form); break; }
    }
    if (next === null) return;
    log('POST', path, '-> redirect', next);
    setTimeout(function () { window.location.href = next; }, 400);
  });

  // OTP page: show the (masked) e-mail the visitor typed on the sign-up form
  document.addEventListener('DOMContentLoaded', function () {
    var el = document.getElementById('protoMaskedEmail');
    var email = '';
    try { email = sessionStorage.getItem('proto_signup_email') || ''; } catch (e) {}
    if (el && email.indexOf('@') > 0) {
      var parts = email.split('@');
      el.textContent = parts[0].charAt(0) + '***@' + parts[1];
    }
  });
})();
